import type {
  PublicTrillionGraph,
  TrillionEdge,
  TrillionNode,
} from "@acme/validators";

/**
 * Reading model for the Trillion screen: tabs, ordering and labels derived from
 * a published graph. Kept free of React so the list, the map and tests agree.
 */

export type Tone =
  | "for"
  | "against"
  | "mixed"
  | "question"
  | "applies"
  | "neutral";
export interface Item {
  edge: TrillionEdge;
  /** "in": the other node points at the focus; "out": the focus points at it. */
  dir: "in" | "out";
}
export interface Category {
  key: string;
  label: string;
  tone: Tone;
  items: Item[];
  empty?: string;
}
export type Step = { t: "node"; id: string } | { t: "edge"; id: string };

export const KIND_LABEL: Record<TrillionNode["kind"], string> = {
  root: "Main case",
  branch: "Start here",
  crux: "Where people disagree",
  provision: "Measure text",
  finding: "Measure findings",
  analysis: "Legislative Analyst",
  argument: "Ballot argument",
  generated: "Generated by Billion",
  question: "Open question",
  shared: "Shared claim",
  record: "Other measure",
  fact: "Fact",
  precedent: "Past record",
};
/** Billion wrote these itself; unverified graphs label them AI-generated. */
export const BILLION_AUTHORED = new Set<TrillionNode["kind"]>([
  "crux",
  "generated",
  "question",
  "shared",
  "fact",
]);

const IN: Partial<Record<TrillionEdge["type"], string>> = {
  supports: "Supports this",
  challenges: "Challenges this",
  qualifies: "Qualifies this",
  appliesTo: "Applies here",
  asks: "Asks about this",
  answers: "Answers this",
  conflicts: "Conflicts with this",
};
const OUT: Record<TrillionEdge["type"], string> = {
  supports: "Supports",
  challenges: "Challenges",
  qualifies: "Qualifies",
  appliesTo: "Applies to",
  asks: "Asks about",
  answers: "Answers",
  conflicts: "Conflicts with",
  detail: "Part of",
  part: "Part of",
  crux: "Disputed under",
  weighs: "Weighs in on",
};
const SHORT: Record<TrillionEdge["type"], string> = {
  supports: "supports",
  challenges: "challenges",
  qualifies: "qualifies",
  appliesTo: "applies to",
  asks: "asks",
  answers: "answers",
  conflicts: "conflicts",
  detail: "",
  part: "",
  crux: "",
  weighs: "",
};
const TONE: Record<TrillionEdge["type"], Tone> = {
  supports: "for",
  challenges: "against",
  qualifies: "mixed",
  conflicts: "mixed",
  asks: "question",
  answers: "question",
  appliesTo: "applies",
  detail: "neutral",
  part: "neutral",
  crux: "neutral",
  weighs: "neutral",
};
const LEAN = { for: "Leans yes", against: "Leans no", mixed: "Cuts both ways" };
export const DISPUTE_LABEL = {
  facts: "Disputed facts",
  values: "Mostly values",
  reading: "Disputed reading of the text",
  legal: "Depends on courts and other measures",
} as const;
/** Billion's nonpartisan outcome hues; always paired with a written label. */
export const TONE_COLOR: Record<Tone, string> = {
  for: "#55D6BE",
  against: "#FF9575",
  mixed: "#B8A1FF",
  question: "#F4C95D",
  applies: "#A5B9FF",
  neutral: "#4A5068",
};

export const tone = (e: TrillionEdge): Tone =>
  e.type === "weighs" && e.stance ? e.stance : TONE[e.type];
export const inLabel = (e: TrillionEdge) =>
  e.type === "weighs" && e.stance
    ? LEAN[e.stance]
    : (IN[e.type] ?? OUT[e.type]);
export const outLabel = (e: TrillionEdge) =>
  e.type === "weighs" && e.stance ? `${LEAN[e.stance]} on` : OUT[e.type];
export const shortLabel = (e: TrillionEdge) =>
  e.type === "weighs" && e.stance
    ? LEAN[e.stance].toLowerCase()
    : SHORT[e.type];

const KIDS = new Set(["part", "detail", "crux"]);
const RESTS = new Set(["supports", "appliesTo"]);
const RESP = new Set([
  "challenges",
  "qualifies",
  "asks",
  "answers",
  "conflicts",
]);

export class TrillionModel {
  readonly nodes: Map<string, TrillionNode>;
  readonly edges: Map<string, TrillionEdge>;
  constructor(readonly graph: PublicTrillionGraph) {
    this.nodes = new Map(graph.nodes.map((n) => [n.id, n]));
    this.edges = new Map(graph.edges.map((e) => [e.id, e]));
  }
  get rootId() {
    return this.graph.rootId;
  }
  node(id: string): TrillionNode {
    const node = this.nodes.get(id);
    if (!node) throw new Error(`Unknown node ${id}`);
    return node;
  }
  incoming(id: string) {
    return this.graph.edges.filter((e) => e.to === id);
  }
  outgoing(id: string) {
    return this.graph.edges.filter((e) => e.from === id);
  }

  /** Debate structure, not popularity: unanswered, then evidenced, then contested. */
  rank(id: string): number {
    const inc = this.incoming(id);
    const kind = this.node(id).kind;
    const answered = inc.some((e) => RESP.has(e.type) || e.type === "supports");
    if ((kind === "question" || kind === "argument") && !answered) return 0;
    if (inc.some((e) => e.type === "supports")) return 1;
    if (inc.some((e) => e.type === "challenges")) return 2;
    return 3;
  }
  private ranked(edges: TrillionEdge[], dir: "in" | "out"): Item[] {
    return [...edges]
      .sort(
        (a, b) =>
          this.rank(dir === "in" ? a.from : a.to) -
          this.rank(dir === "in" ? b.from : b.to),
      )
      .map((edge) => ({ edge, dir }));
  }

  /** A disputed question's state says where the debate stands, never who leads. */
  cruxState(id: string): { open: number; text: string } {
    const args = this.incoming(id).filter((e) => e.type === "weighs");
    const open = args.filter((e) => this.rank(e.from) === 0).length;
    const sides = new Set(args.map((e) => e.stance));
    const state = open
      ? `${open} unanswered`
      : sides.has("for") && sides.has("against")
        ? "Contested"
        : "Few arguments yet";
    const dispute = this.node(id).dispute;
    return {
      open,
      text: `${dispute ? DISPUTE_LABEL[dispute] : "Disputed"} · ${state}`,
    };
  }

  /** Everything in the record nobody has responded to yet, shown against its target. */
  unanswered(): Item[] {
    return this.graph.nodes
      .filter((n) => n.id !== this.rootId && this.rank(n.id) === 0)
      .flatMap((n) => {
        const edge = this.outgoing(n.id)[0];
        return edge ? [{ edge, dir: "in" as const }] : [];
      });
  }

  categories(id: string): Category[] {
    const inc = this.incoming(id);
    const out = this.outgoing(id);
    if (id === this.rootId)
      return [
        {
          key: "basics",
          label: "Basics",
          tone: "neutral",
          items: inc
            .filter((e) => e.type === "part")
            .map((edge) => ({ edge, dir: "in" })),
        },
        {
          key: "disagree",
          label: "Disputes",
          tone: "neutral",
          items: inc
            .filter((e) => e.type === "crux")
            .sort(
              (a, b) =>
                this.cruxState(b.from).open - this.cruxState(a.from).open,
            )
            .map((edge) => ({ edge, dir: "in" })),
        },
        {
          key: "open",
          label: "Unanswered",
          tone: "question",
          items: this.unanswered(),
          empty: "Everything here has at least one response.",
        },
      ];
    const kind = this.node(id).kind;
    if (kind === "crux")
      return [
        {
          key: "args",
          label: "Arguments",
          tone: "neutral",
          items: this.ranked(
            inc.filter((e) => e.type === "weighs"),
            "in",
          ),
        },
        {
          key: "resp",
          label: "Questions about this",
          tone: "question",
          items: this.ranked(
            inc.filter((e) => RESP.has(e.type)),
            "in",
          ),
          empty: "No one has questioned how this dispute is framed.",
        },
      ];
    const categories: Category[] = [];
    const kids = inc.filter((e) => e.type === "detail" || e.type === "part");
    if (kids.length)
      categories.push({
        key: "inside",
        label: "Inside",
        tone: "neutral",
        items: kids.map((edge) => ({ edge, dir: "in" })),
      });
    if (kind !== "branch") {
      categories.push({
        key: "resp",
        label: "Responses",
        tone: "against",
        items: this.ranked(
          inc.filter((e) => RESP.has(e.type)),
          "in",
        ),
        empty: "No one has challenged, qualified, or questioned this yet.",
      });
      categories.push({
        key: "rests",
        label: "Rests on",
        tone: "for",
        items: this.ranked(
          inc.filter((e) => RESTS.has(e.type)),
          "in",
        ),
        empty: ["provision", "finding"].includes(kind)
          ? "This is the measure's own wording. Read the source to see it in context."
          : "No supporting evidence or reasons have been linked yet.",
      });
    }
    if (out.length)
      categories.push({
        key: "used",
        label: "Used in",
        tone: "applies",
        items: out.map((edge) => ({ edge, dir: "out" })),
      });
    return categories;
  }

  defaultTab(id: string): string {
    const cats = this.categories(id);
    return (
      (
        cats.find((c) => ["inside", "basics", "args"].includes(c.key)) ??
        cats.find((c) => c.items.length) ??
        cats[0]
      )?.key ?? ""
    );
  }

  /**
   * The cards the map shows: main case, focus, previous step and the open tab,
   * plus one grayed grandchild under each tab card (`hints`, also in `nodes`)
   * chosen the way that card's own page would open.
   */
  lit(
    path: Step[],
    tab: string,
  ): {
    focus: string;
    prev: string | null;
    nodes: string[];
    edges: string[];
    hints: string[];
  } {
    const current = path[path.length - 1]!;
    const focus =
      current.t === "edge" ? this.edges.get(current.id)!.to : current.id;
    const nodes = new Set([focus, this.rootId]);
    const edges = new Set<string>();
    if (current.t === "edge") {
      nodes.add(this.edges.get(current.id)!.from);
      edges.add(current.id);
    } else {
      const cat = this.categories(focus).find((c) => c.key === tab);
      for (const { edge, dir } of cat?.items ?? []) {
        nodes.add(dir === "in" ? edge.from : edge.to);
        if ((dir === "in" ? edge.to : edge.from) === focus) edges.add(edge.id);
      }
    }
    const before = path.length > 1 ? path[path.length - 2] : undefined;
    const prev = before?.t === "node" ? before.id : null;
    if (prev) nodes.add(prev);
    for (const e of this.graph.edges)
      if (
        nodes.has(e.from) &&
        nodes.has(e.to) &&
        (e.from === focus || e.to === focus)
      )
        edges.add(e.id);
    const hints: string[] = [];
    if (current.t === "node")
      for (const { edge, dir } of this.categories(focus).find(
        (c) => c.key === tab,
      )?.items ?? []) {
        const child = dir === "in" ? edge.from : edge.to;
        const first = (
          this.categories(child).find((c) => c.key === this.defaultTab(child))
            ?.items ?? []
        )
          .map((item) => ({
            id: item.dir === "in" ? item.edge.from : item.edge.to,
            edge: item.edge.id,
          }))
          .find((g) => !nodes.has(g.id) && !hints.includes(g.id));
        if (first) {
          hints.push(first.id);
          edges.add(first.edge);
        }
      }
    return {
      focus,
      prev,
      nodes: [...nodes, ...hints],
      edges: [...edges],
      hints,
    };
  }
}
