export function readerLabel(
  language: "en" | "es" | "zh",
  key: string,
  values: Record<string, string | number> = {},
) {
  const singular: Record<string, string> = {
    "{count} arguments": "1 argument",
    "{count} items": "1 item",
    "{count} quotes": "1 quote",
  };
  const resolvedKey = values.count === 1 ? (singular[key] ?? key) : key;
  const text =
    language === "en"
      ? resolvedKey
      : (labels[resolvedKey]?.[language] ?? resolvedKey);
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    String(values[name] ?? match),
  );
}
